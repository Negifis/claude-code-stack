"""
PreToolUse guard against comment bloat in source, config, script and IaC files.

Prompt rules decay; this is the mechanical floor under them. Deterministic and local —
no model call, no network, a few milliseconds on top of interpreter startup.

It reads only the lines an edit *adds*, and only plain comments among them. Doc comments
(docstrings, JSDoc, `///`), machine-readable directives (lint pragmas, build tags,
shebangs) and licence or generated-file boilerplate are never counted, so an API doc, a
`# type: ignore` or an Apache header can never trip it.

Three shapes deny:

  BLOAT      many added comment lines against little added code — the paragraph that
             explains a one-liner.
  BLOCK      a long unbroken comment run attached to a small change.
  NARRATION  the conversation leaking into the repository.

NARRATION is split by how much the phrasing can mean something else. The hard set —
first-person process, the user, sessions, attempts, rejected options — has no innocent
reading and applies everywhere, tag or no tag. The soft set — "previously this…", "used
to be", "turned out" — reads as history in a bare comment and as legitimate context
inside a declared one, so a run that opens with SAFETY:/SECURITY:/WORKAROUND:/INVARIANT:/
COMPAT:/ALGORITHM: or cites a checkable source (URL, CVE, RFC, tracker id) is exempt from
it, and from BLOAT and BLOCK. That exemption is a claim, not a bypass: the hard set still
applies, and a declared run still cannot outrun TAGGED_CEILING on a change this small.

Two known limits, pulling opposite ways. A `#` or `//` line inside a string literal counts
as a comment, so comment-shaped text in a heredoc can deny an edit that deserved to pass —
bounded by the strike budget, not eliminated. A block whose opener sits outside the added
window is not recognised as one, which under-counts comments and lets an edit through.

Fails open on anything unexpected — unreadable file, malformed payload, unwritable state.
After GIVE_UP_AFTER denials on one file the guard only warns, so it can never deadlock a
task. Set CLAUDE_COMMENT_GUARD=off to disable it entirely.
"""
import json
import os
import re
import sys

MIN_COMMENTS = 5          # below this, no ratio is worth acting on
CODE_RATIO = 3            # comments must exceed this multiple of added code
MAX_RUN = 8               # unbroken comment lines...
RUN_CODE_CEILING = 2      # ...against at most this much added code
TAGGED_CEILING = 10       # a declared run is still not licence for an essay
GIVE_UP_AFTER = 2         # denials per file before the guard steps aside

LINE_TOKENS = {
    "#": (".py .pyi .sh .bash .zsh .fish .rb .pl .r .jl .toml .yaml .yml .ini .conf .cfg "
          ".tf .tfvars .hcl .nix .ps1 .psm1 .psd1 .mk .properties .service .env .rc "
          ".gitignore .dockerignore .editorconfig .cmake"),
    "//": (".js .mjs .cjs .jsx .ts .tsx .mts .cts .go .rs .java .c .h .cpp .hpp .cxx .hxx "
           ".cc .cs .kt .kts .swift .scala .php .dart .proto .groovy .gradle .sol .zig .v "
           ".json5 .jsonc .glsl .hlsl .ino .pde"),
    "--": ".sql .lua .hs .elm .adb .ads .vhd .vhdl",
    ";": ".el .lisp .clj .cljs .cljc .scm .asm .s .reg .nsi",
}
EXT_TOKEN = {ext: token for token, exts in LINE_TOKENS.items() for ext in exts.split()}
NAMED_FILES = {"dockerfile": "#", "makefile": "#", "jenkinsfile": "//", "vagrantfile": "#",
               "gemfile": "#", "rakefile": "#", "brewfile": "#", "justfile": "#",
               "caddyfile": "#", "procfile": "#"}

BLOCK_LANGS = {"//"}
SKIP_PATH = re.compile(
    r"(^|[\\/])(node_modules|vendor|\.git|dist|build|out|target|\.venv|venv|site-packages|"
    r"__pycache__|\.next|\.nuxt|coverage|third_party)([\\/]|$)", re.I)
SKIP_NAME = re.compile(r"\.(min|bundle|generated|g|pb|lock)\.[a-z0-9]+$|_pb2\.py$", re.I)

# Boilerplate whose length someone else decides. Never measured.
BOILERPLATE = re.compile(
    r"^\s*[*\-]?\s*(licen[sc]e|copyright|spdx-[a-z-]+|@generated|code generated by|"
    r"do not edit|autogenerated|generated by|@license|@preserve)\b", re.I)

# Exactly the categories the deny message offers. An undocumented tag is a silent bypass.
TAGGED = re.compile(
    r"^\s*[*\-]?\s*(safety|security|invariant|workaround|compat|compatibility|algorithm)\b",
    re.I)

DIRECTIVE = re.compile(
    r"^!|^\s*-\*-|\b(type:\s*ignore|noqa|pylint:|pyright:|mypy:|ruff:|flake8:|fmt:\s*(on|off)|"
    r"isort:|nosec|bandit|pragma|eslint|prettier|tslint:|biome-ignore|istanbul ignore|"
    r"c8 ignore|v8 ignore|jshint|jslint|globals\s|deno-lint-ignore|stylelint|codespell|"
    r"cspell|spell-checker|sourceMappingURL|go:generate|go:build|go:embed|go:linkname|"
    r"\+build|nolint|golangci|shellcheck|hadolint|checkstyle|swiftlint|ktlint|rubocop|"
    r"frozen_string_literal|encoding:|vim:|emacs:|region\b|endregion\b|@ts-(ignore|"
    r"expect-error|nocheck)|@flow|@jsx|@license|@preserve|#include|#define|#if|#endif)",
    re.I)

EXTERNAL_REF = re.compile(
    r"https?://|\bCVE-\d{4}-\d+|\bRFC\s?\d{3,}|\b(?:bug|issue|ticket|pr)\s*#?\d{2,}\b|"
    r"\b[a-z][\w.-]*#\d{2,}\b|\b(?:upstream|vendor|kernel|firmware|driver|browser)\b"
    r".{0,40}\b(?:bug|issue|defect|regression|limitation|quirk)\b", re.I)

# No innocent reading: process, people, sessions. Applies inside declared runs too.
# Each phrase must carry its narrative object — bare, these same words describe runtime
# behaviour in ordinary CLI, transactional and retry code.
NARRATION_HARD = re.compile(
    r"\b(?:we|i) (?:tried|attempted|discovered|initially|switched|decided|realised|"
    r"realized)\b|\bthe user (?:asked|wanted|requested) (?:for )?(?:this|us|me)\b|"
    r"\bin (?:this|the previous|the last) (?:session|conversation|turn)\b|"
    r"\bas (?:discussed|mentioned|noted) (?:above|earlier|before)\b|"
    r"\bbefore (?:this|the) (?:change|fix|patch)\s*[,:;]|"
    r"\b(?:our|my) (?:first|second|third) attempt\b|"
    r"^(?:our |my )?(?:first|second|third) attempt (?:failed|was wrong|didn't|did not)\b|"
    r"\brejected (?:this|that|the) (?:approach|option|alternative|idea)\b|"
    r"\bafter (?:much|hours|days|several|some)\b.{0,20}\b(?:debugging|investigation|"
    r"digging|attempts|tries|testing)\b|"
    r"^(?:background|history)\s*:|"
    r"\bпользовател[ья] (?:просил|попросил|хотел) (?:это|этого|об этом|нас|меня)\b|"
    r"\bмы (?:пробовали|решили|выяснили)\b", re.I)

# History in a bare comment, context inside a declared one. Skipped for declared runs.
# The Russian tokens need the continuation their English counterparts carry: alone they
# modify a noun and describe the code as it stands.
NARRATION_SOFT = re.compile(
    r"^previously\b|\bpreviously[,: ]+(?:this|it|we|i|the code|the implementation|"
    r"the config|the default|the value)\b|\bused to be\b|\bturned out\b|"
    r"\bthis (?:was|used to be) an? (?:bug|hack|workaround)\b|"
    r"\bthe (?:root )?cause (?:was|turned out)\b|\b(?:postmortem|post-mortem)\b|"
    r"\b(?:раньше|ранее|изначально)\s+(?:тут|здесь|это|мы|был|было|была|были|стоял|"
    r"стояло|стояла|использовал|работал|делал)\w*\b|\b(?:оказалось|выяснилось)\b", re.I)

VERDICTS = {
    "BLOAT": "{c} added comment lines against {k} added code lines",
    "BLOCK": "an unbroken {run}-line comment run against {k} added code lines",
    "NARRATION": "the conversation leaking into a comment: {quote}",
}

REASON = (
    "[Comment guard] This edit to {path} was not applied — {detail}.\n"
    "Rebuild it dense instead of resubmitting it:\n"
    "- keep only what the code cannot hold — rationale, invariant, constraint, hazard, the "
    "reason a future reader would otherwise revert this;\n"
    "- drop investigation history, attempts, rejected options, \"used to be X\", restatements "
    "of the task, the ticket or the diff — the file must read as if the answer was known from "
    "the start;\n"
    "- an obvious change gets no comment; a non-obvious one usually gets one line.\n"
    "If the long form is genuinely load-bearing, open the first line with the category it "
    "belongs to — SAFETY:, SECURITY:, WORKAROUND:, INVARIANT:, COMPAT:, ALGORITHM:, LICENSE: or "
    "@generated — or cite the source it rests on (URL, CVE, RFC, tracker id), and keep every "
    "line load-bearing."
)


def emit(payload):
    print(json.dumps(payload, ensure_ascii=False))


def bare(line):
    """A comment line with its marker and decoration stripped."""
    return line.strip().lstrip("*/#-; ").strip()


def narration(run, pattern):
    """First narration verdict in a comment run, or None."""
    for text in run:
        if pattern.search(text):
            return "NARRATION", {"quote": text[:90]}
    return None


def token_for(path):
    name = os.path.basename(path or "").lower()
    if name in NAMED_FILES:
        return NAMED_FILES[name]
    # A dotfile is its own extension: splitext(".gitignore") yields no extension at all.
    ext = os.path.splitext(name)[1] or (name if name.startswith(".") else "")
    return EXT_TOKEN.get(ext)


def classify(lines, token):
    """Tag each line code / comment / skip. Doc comments and directives are skipped."""
    out = []
    block = None          # None | "plain" | "doc"
    triple = None
    # Precomputed so k unclosed openers cost one scan between them, not k scans to the end.
    close_after = [False] * (len(lines) + 1)
    for i in range(len(lines) - 1, -1, -1):
        close_after[i] = close_after[i + 1] or ("*/" in lines[i])
    for index, raw in enumerate(lines):
        line = raw.strip()
        if triple:
            out.append("skip")
            if triple in line:
                triple = None
            continue
        if block:
            out.append("comment" if block == "plain" else "skip")
            if "*/" in line:
                block = None
            continue
        if not line:
            out.append("skip")
            continue
        if token == "#" and line.startswith(('"""', "'''")):
            mark = line[:3]
            # An opener whose close is outside the window is more likely a stray closer;
            # reading it as an opener would swallow every following line.
            if line.count(mark) < 2 and any(mark in l for l in lines[index + 1:]):
                triple = mark
            out.append("skip")
            continue
        if token in BLOCK_LANGS and line.startswith("/*"):
            kind = "doc" if line.startswith("/**") else "plain"
            if "*/" not in line[2:] and close_after[index + 1]:
                block = kind
            out.append("comment" if kind == "plain" else "skip")
            continue
        if token == "//" and line.startswith(("///", "//!")):
            out.append("skip")
            continue
        if line.startswith(token):
            out.append("skip" if DIRECTIVE.search(line[len(token):]) else "comment")
            continue
        out.append("code")
    return out


def added_lines(old, new):
    """Lines present in `new` beyond what `old` already had. Moved lines are not added."""
    pool = {}
    for line in (old or "").splitlines():
        key = line.strip()
        pool[key] = pool.get(key, 0) + 1
    kept = []
    for line in (new or "").splitlines():
        key = line.strip()
        if pool.get(key):
            pool[key] -= 1
        else:
            kept.append(line)
    return kept


def collect(tool, payload, path):
    """Lines this edit adds, per tool shape. An unreadable old file contributes none."""
    if tool == "Write":
        try:
            with open(path, encoding="utf-8", errors="replace") as f:
                old = f.read()
        except FileNotFoundError:
            old = ""
        except OSError:
            # Cannot tell new content from old, so cannot judge the edit at all.
            return []
        return added_lines(old, payload.get("content"))
    if tool == "MultiEdit":
        lines = []
        for edit in payload.get("edits") or []:
            if isinstance(edit, dict):
                lines += added_lines(edit.get("old_string"), edit.get("new_string"))
        return lines
    return added_lines(payload.get("old_string"), payload.get("new_string"))


def inspect(lines, token):
    """Return (verdict, detail_fields) for the added lines, or None when they are fine."""
    kinds = classify(lines, token)
    code = sum(1 for k in kinds if k == "code")

    runs, current = [], []
    for line, kind in zip(lines, kinds):
        if kind == "comment":
            current.append(bare(line))
        elif current:
            runs.append(current)
            current = []
    if current:
        runs.append(current)

    plain_runs = []
    for run in runs:
        hit = narration(run, NARRATION_HARD)
        if hit:
            return hit
        if BOILERPLATE.search(run[0]):
            continue
        declared = bool(TAGGED.search(run[0]) or EXTERNAL_REF.search(" ".join(run)))
        if not declared:
            hit = narration(run, NARRATION_SOFT)
            if hit:
                return hit
        # Kept even when declared: TAGGED_CEILING still caps it.
        plain_runs.append((len(run), declared))

    longest = max([n for n, _ in plain_runs] or [0])
    if longest >= TAGGED_CEILING and code <= RUN_CODE_CEILING:
        return "BLOCK", {"run": longest, "k": code}

    lengths = [n for n, declared in plain_runs if not declared]
    counted = sum(lengths)
    if counted >= MIN_COMMENTS and counted > CODE_RATIO * code:
        return "BLOAT", {"c": counted, "k": code}
    if lengths and max(lengths) >= MAX_RUN and code <= RUN_CODE_CEILING:
        return "BLOCK", {"run": max(lengths), "k": code}
    return None


def strikes(session, path):
    """
    Denials so far for this file, or a spent budget when the count cannot be kept.

    A count that never advances would keep denying the same file forever, so every
    persistence failure reports the budget as already spent.
    """
    tmp = os.environ.get("TMPDIR") or os.environ.get("TEMP") or os.environ.get("TMP")
    if not tmp or not os.path.isdir(tmp):
        return GIVE_UP_AFTER + 1
    store = os.path.join(tmp, "cdg_{}.json".format(
        "".join(c if c.isalnum() or c in "-_" else "_" for c in str(session or "x"))[:64]))
    data = {}
    try:
        with open(store, encoding="utf-8") as f:
            data = json.load(f)
    except FileNotFoundError:
        pass
    except Exception:
        data = {}
    if not isinstance(data, dict):
        data = {}
    key = str(path).replace("\\", "/").lower()
    try:
        count = int(data.get(key) or 0) + 1
    except (TypeError, ValueError):
        count = 1
    data[key] = count
    scratch = "{}.{}.tmp".format(store, os.getpid())
    try:
        with open(scratch, "w", encoding="utf-8") as f:
            json.dump(data, f)
        os.replace(scratch, store)
    except Exception:
        try:
            os.remove(scratch)
        except OSError:
            pass
        return GIVE_UP_AFTER + 1
    return count


def main():
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
        sys.stdin.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass
    allow = {"continue": True, "suppressOutput": True}
    try:
        if os.environ.get("CLAUDE_COMMENT_GUARD", "").lower() in ("off", "0", "false"):
            emit(allow)
            return
        data = json.loads(sys.stdin.read())
        tool = data.get("tool_name")
        args = data.get("tool_input")
        if tool not in ("Edit", "Write", "MultiEdit") or not isinstance(args, dict):
            emit(allow)
            return
        path = args.get("file_path") or ""
        token = token_for(path)
        if not token or SKIP_PATH.search(path) or SKIP_NAME.search(path):
            emit(allow)
            return
        lines = collect(tool, args, path)
        found = inspect(lines, token) if lines else None
        if not found:
            emit(allow)
            return
        verdict, fields = found
        text = REASON.format(path=os.path.basename(path),
                             detail=VERDICTS[verdict].format(**fields))
        if strikes(data.get("session_id"), path) > GIVE_UP_AFTER:
            allow["hookSpecificOutput"] = {
                "hookEventName": "PreToolUse",
                "additionalContext": text + "\n(Strike budget for this file is spent — applied "
                                            "anyway. Make it dense before you finish.)",
            }
        else:
            allow["hookSpecificOutput"] = {
                "hookEventName": "PreToolUse",
                "permissionDecision": "deny",
                "permissionDecisionReason": text,
            }
    except Exception:
        allow = {"continue": True, "suppressOutput": True}
    emit(allow)


if __name__ == "__main__":
    main()
